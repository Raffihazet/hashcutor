def analisis_keuangan():

    pemasukan = user()["pemasukan"]
    pengeluaran = user()["pengeluaran"]

    if pemasukan <= 0:
        return print("\nMasih belum ada data pemasukan")

    rasio = (pengeluaran / pemasukan) * 100

    print("\n=== ANALISIS KEUANGAN ===")
    print(f"Rasio pengeluaran : {rasio:.1f}%")

    if rasio >= 90:

        print("Pengeluaran kamu udah terlalu tinggi")
        print("- Kurangi belanja impulsif")
        print("- Fokus nabung dulu")

    elif rasio >= 70:

        print("Pengeluaran mulai lumayan besar")
        print("- Coba lebih hemat lagi")

    else:

        print("Cashflow kamu masih aman")
        print("- Pertahankan kebiasaan ini")

