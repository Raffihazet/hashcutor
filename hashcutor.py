def input_pengeluaran():

    kategori_map = {
        "1": ("Kebutuhan", KEBUTUHAN, "detail_kebutuhan"),
        "2": ("Keinginan", KEINGINAN, "detail_keinginan")
    }

    print("\n1. Kebutuhan")
    print("2. Keinginan")

    kategori = input("Pengeluaran ini termasuk apa? : ").strip()

    if kategori not in kategori_map:
        return print("Kategori nggak tersedia")

    nama, detail_map, key = kategori_map[kategori]

    try:

        jumlah = float(input("Keluar berapa? Rp "))

        if jumlah <= 0:
            return print("Nominal nggak valid")

    except:
        return print("Input harus angka")

    print()

    for k, v in detail_map.items():
        print(f"{k}. {v}")

    pilih = input("Pilih detail pengeluaran : ").strip()

    if pilih not in detail_map:
        return print("Pilihan detail nggak tersedia")

    detail = detail_map[pilih]

    data = {
        "tanggal": tanggal(),
        "detail": detail,
        "jumlah": jumlah
    }

    user()["pengeluaran"] += jumlah

    user()[key].append(data)

    user()["kategori_pengeluaran"].append({
        "tanggal": tanggal(),
        "kategori": nama,
        "detail": detail,
        "jumlah": jumlah
    })

    user()["riwayat_transaksi"].append({
        "tanggal": tanggal(),
        "jenis": "Pengeluaran",
        "detail": detail,
        "jumlah": jumlah
    })

    save_users()

    print("\nPengeluaran berhasil dicatat")

