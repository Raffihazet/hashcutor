def reset_aman():

    backup = {
        "tanggal": tanggal(),
        "pemasukan": user()["pemasukan"],
        "pengeluaran": user()["pengeluaran"],
        "tabungan": user()["tabungan"],
        "emas_gram": user()["emas_gram"]
    }

    user()["backups"].append(backup)

    print("\nBackup data berhasil dibuat")

    if input("Ketik RESET kalau yakin : ").upper() == "RESET":

        user()["pemasukan"] = 0
        user()["pengeluaran"] = 0
        user()["tabungan"] = 0
        user()["emas_gram"] = 0
        user()["total_beli_emas"] = 0

        save_users()

        print("Semua data berhasil direset")

# ==========================================================
# RESTORE BACKUP
# ==========================================================

def restore_backup():

    backups = user()["backups"]

    if not backups:
        return print("Belum ada backup yang tersimpan")

    print("\n=== BACKUP TERSEDIA ===")

    for i, b in enumerate(backups[-3:], 1):
        print(f"{i}. {b['tanggal']}")

    try:

        pilih = int(input("Pilih backup yang mau dipulihkan : ")) - 1

        data = backups[pilih]

        user()["pemasukan"] = data["pemasukan"]
        user()["pengeluaran"] = data["pengeluaran"]
        user()["tabungan"] = data["tabungan"]
        user()["emas_gram"] = data["emas_gram"]

        save_users()

        print("Backup berhasil dipulihkan")

    except:
        print("Pilihan nggak valid")

